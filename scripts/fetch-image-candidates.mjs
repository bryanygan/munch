// Fetches image candidates from Pexels (and optionally Unsplash) for every
// dish in foods.json whose image_url is a picsum.photos placeholder.
// Output: scripts/image-candidates.js (assigns window.CANDIDATES for the picker UI).
//
// Flags:
//   --include-unsplash   Also query Unsplash (demo tier is 50 req/hr — slow).
//   --refresh            Re-query dishes that already have candidates saved.
//   --limit N            Only process the first N placeholder dishes (for testing).
//
// Rerun-friendly: saves progress every 5 dishes; on 429 sleeps 60s and retries.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const FOODS_PATH = path.join(ROOT, 'mobile', 'src', 'data', 'foods.json');
const OUT_PATH = path.join(ROOT, 'scripts', 'image-candidates.js');
const ENV_PATH = path.join(ROOT, '.env');

// --- Parse .env manually (no dotenv dep) ---
const env = {};
if (fs.existsSync(ENV_PATH)) {
  for (const line of fs.readFileSync(ENV_PATH, 'utf-8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/i);
    if (m) env[m[1]] = m[2];
  }
}

const PEXELS_KEY = env.PEXELS_API_KEY;
const UNSPLASH_KEY = env.UNSPLASH_ACCESS_KEY;
if (!PEXELS_KEY) {
  console.error('Missing PEXELS_API_KEY in .env');
  process.exit(1);
}

// --- Flags ---
const flags = new Set(process.argv.slice(2).filter(a => a.startsWith('--') && !a.includes('=')));
const args = Object.fromEntries(
  process.argv.slice(2).filter(a => a.includes('=')).map(a => a.replace(/^--/, '').split('=')),
);
const INCLUDE_UNSPLASH = flags.has('--include-unsplash') && !!UNSPLASH_KEY;
const REFRESH = flags.has('--refresh');
const LIMIT = args.limit ? parseInt(args.limit, 10) : Infinity;

// --- Load existing progress ---
let existing = {};
if (fs.existsSync(OUT_PATH) && !REFRESH) {
  const src = fs.readFileSync(OUT_PATH, 'utf-8');
  const m = src.match(/window\.CANDIDATES\s*=\s*(\{[\s\S]*\})\s*;?\s*$/);
  if (m) {
    try { existing = JSON.parse(m[1]); } catch { existing = {}; }
  }
}

// --- Load foods ---
const dishes = JSON.parse(fs.readFileSync(FOODS_PATH, 'utf-8'));
const placeholders = dishes.filter(d => /picsum\.photos/.test(d.image_url));
console.log(`Found ${placeholders.length} dishes with placeholder images (total: ${dishes.length}).`);

const todo = placeholders.filter(d => REFRESH || !existing[d.id]).slice(0, LIMIT);
console.log(`Will fetch candidates for ${todo.length} dishes (already done: ${placeholders.length - todo.length}).`);
if (todo.length === 0) { console.log('Nothing to do.'); process.exit(0); }

// --- Helpers ---
const sleep = ms => new Promise(r => setTimeout(r, ms));

async function fetchWithRetry(url, init, maxRetries = 4) {
  for (let attempt = 0; attempt <= maxRetries; attempt++) {
    const res = await fetch(url, init);
    if (res.status === 429) {
      const retryAfter = parseInt(res.headers.get('retry-after') || '60', 10);
      console.warn(`  429 from ${new URL(url).host} — sleeping ${retryAfter}s`);
      await sleep(retryAfter * 1000);
      continue;
    }
    if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
    return res.json();
  }
  throw new Error(`Rate-limit retry exhausted for ${url}`);
}

async function pexelsSearch(query) {
  const url = `https://api.pexels.com/v1/search?query=${encodeURIComponent(query)}&per_page=6&orientation=landscape`;
  const data = await fetchWithRetry(url, { headers: { Authorization: PEXELS_KEY } });
  return (data.photos || []).map(p => ({
    provider: 'pexels',
    id: String(p.id),
    thumb: p.src.medium,
    full: p.src.large2x || p.src.large,
    photographer: p.photographer,
    source_page: p.url,
    alt: p.alt || '',
  }));
}

async function unsplashSearch(query) {
  const url = `https://api.unsplash.com/search/photos?query=${encodeURIComponent(query)}&per_page=4&orientation=landscape&client_id=${UNSPLASH_KEY}`;
  const data = await fetchWithRetry(url, { headers: { 'Accept-Version': 'v1' } });
  return (data.results || []).map(p => ({
    provider: 'unsplash',
    id: p.id,
    thumb: p.urls.small,
    full: `${p.urls.raw}&w=1600&q=80&auto=format&fit=max`,
    photographer: p.user?.name,
    source_page: p.links?.html,
    alt: p.alt_description || '',
  }));
}

function saveProgress(data) {
  const body = `// Auto-generated by scripts/fetch-image-candidates.mjs — do not edit by hand.\n` +
    `// Regenerate with: node scripts/fetch-image-candidates.mjs\n` +
    `window.CANDIDATES = ${JSON.stringify(data, null, 2)};\n`;
  fs.writeFileSync(OUT_PATH, body);
}

// --- Main loop ---
const out = { ...existing };
let done = 0;
for (const dish of todo) {
  const query = dish.name;
  process.stdout.write(`[${++done}/${todo.length}] ${dish.id} :: "${query}" ... `);
  try {
    const pexels = await pexelsSearch(query);
    let unsplash = [];
    if (INCLUDE_UNSPLASH) {
      await sleep(100);
      try { unsplash = await unsplashSearch(query); }
      catch (e) { console.warn(`\n    unsplash failed: ${e.message}`); }
    }
    const candidates = [...pexels, ...unsplash];
    out[dish.id] = { name: dish.name, description: dish.description, candidates };
    console.log(`pexels:${pexels.length}${INCLUDE_UNSPLASH ? ` unsplash:${unsplash.length}` : ''}`);
  } catch (e) {
    console.error(`FAILED: ${e.message}`);
    out[dish.id] = { name: dish.name, description: dish.description, candidates: [], error: e.message };
  }
  if (done % 5 === 0) saveProgress(out);
  await sleep(150);  // gentle pacing
}

saveProgress(out);
console.log(`\nSaved ${Object.keys(out).length} dish entries to scripts/image-candidates.js`);
console.log('Next: open scripts/image-picker.html in your browser.');
